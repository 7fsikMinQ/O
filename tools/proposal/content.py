def callout(t, k=''):
    return f'<div class="callout {k}">{t}</div>'
def tbl(heads, rows, cls='', widths=None):
    th = ''.join(f'<th>{h}</th>' for h in heads)
    tb = ''.join('<tr>'+''.join(f'<td>{c}</td>' for c in r)+'</tr>' for r in rows)
    cg = ''
    if widths: cg = '<colgroup>'+''.join(f'<col style="width:{w}">' for w in widths)+'</colgroup>'
    return f'<table class="dt {cls}">{cg}<thead><tr>{th}</tr></thead><tbody>{tb}</tbody></table>'
def ul(items): return '<ul>'+''.join(f'<li>{i}</li>' for i in items)+'</ul>'
def ol(items): return '<ol>'+''.join(f'<li>{i}</li>' for i in items)+'</ol>'
def sid(*ids):
    return ' '.join(f'<span class="sid">{i}</span>' for i in ids)
def src(t, u): return f'<a href="{u}">{t}</a>'

